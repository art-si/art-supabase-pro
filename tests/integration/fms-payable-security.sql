begin;
do $test$
declare
  platform_actor uuid;
  ordinary_actor uuid;
  platform_tenant uuid;
  ordinary_tenant uuid;
  other_tenant uuid;
  fixture_role uuid;
  fixture_code text:='PAYABLE_TEST_'||left(gen_random_uuid()::text,8);
  supplier uuid;
  material uuid;
  inventory_unit uuid;
  document_type uuid;
  payload jsonb;
  document jsonb;
  document_id uuid;
  term_id uuid;
  blocked boolean;
  listing jsonb;
begin
  select auth_user_id,tenant_id into platform_actor,platform_tenant from public.sys_user where auth_user_id is not null and user_roles @>array['R_SUPER'] limit 1;
  select account.auth_user_id,account.tenant_id into ordinary_actor,ordinary_tenant from public.sys_user account where account.auth_user_id is not null and account.status='1' and not account.user_roles @>array['R_SUPER'] and exists(select 1 from public.mdm_material where tenant_id=account.tenant_id and status='enabled') and exists(select 1 from public.mdm_supplier where tenant_id=account.tenant_id) limit 1;
  if platform_actor is null or ordinary_actor is null then raise exception 'Missing tenant-matrix fixtures'; end if;
  other_tenant:=platform_tenant;
  insert into public.sys_role(role_name,role_code,enabled,tenant_id) values('应付测试临时角色',fixture_code,true,ordinary_tenant) returning id into fixture_role;
  insert into public.sys_role_menu(role_id,menu_id,tenant_id) select fixture_role,id,ordinary_tenant from public.sys_menu where name in ('FinanceEstimatedPayable:View','FinanceEstimatedPayable:Add','FinanceEstimatedPayable:Edit','MdmPaymentTerm:View','MdmPaymentTerm:Add','MdmPaymentTerm:Edit');
  update public.sys_user set user_roles=array[fixture_code] where auth_user_id=ordinary_actor;
  select id,inventory_unit_id into material,inventory_unit from public.mdm_material where tenant_id=ordinary_tenant and status='enabled' and inventory_unit_id is not null limit 1;
  select id into supplier from public.mdm_supplier where tenant_id=ordinary_tenant limit 1;
  select id into document_type from public.mdm_document_type where tenant_id=ordinary_tenant and document_type_code='AP_EST_STANDARD';
  payload:=jsonb_build_object('kind','estimated','tenant_id',ordinary_tenant,'supplier_id',supplier,'document_type_id',document_type,'business_date','2026-10-21','lines',jsonb_build_array(jsonb_build_object('material_id',material,'inventory_unit_id',inventory_unit,'quantity',1,'unit_price',100,'tax_rate',13)));
  perform set_config('request.jwt.claim.sub',platform_actor::text,true);
  perform set_config('request.headers','{}',true);
  document:=public.fms_save_purchase_payable_secure(payload);
  document_id:=(document->>'id')::uuid;
  if (document->>'tenant_id')::uuid<>ordinary_tenant then raise exception 'Platform-all explicit create lost target tenant'; end if;
  listing:=public.fms_payable_currency_context_secure('estimated','2026-10-21','CNY',ordinary_tenant,document_id);
  if not(listing->>'configured')::boolean or(listing->>'exchange_rate')::numeric<>1 then raise exception 'Platform-all currency context lost inherited tenant';end if;
  document:=public.fms_save_purchase_payable_secure(document||jsonb_build_object('remark','平台全部租户编辑'));
  if document->>'remark'<>'平台全部租户编辑' then raise exception 'Platform-all edit failed'; end if;
  term_id:=public.mdm_save_payment_term_secure(jsonb_build_object('code',fixture_code,'name','平台根记录测试','days',30));
  if (select tenant_id from public.mdm_payment_term where id=term_id)<>platform_tenant then raise exception 'Platform-all root did not default to authenticated platform tenant'; end if;
  perform set_config('request.headers',jsonb_build_object('x-art-tenant-scope',ordinary_tenant)::text,true);
  listing:=public.fms_purchase_payable_list_secure('estimated','',document_id,20,0,'{}');
  if jsonb_array_length(listing->'data')<>1 then raise exception 'Platform-selected could not read target'; end if;
  blocked:=false;begin perform public.fms_payable_currency_context_secure('estimated','2026-10-21','CNY',other_tenant,null);exception when insufficient_privilege then blocked:=true;end;
  if not blocked then raise exception 'Platform-selected currency context crossed selected scope';end if;
  blocked:=false;
  begin perform public.mdm_save_payment_term_secure(jsonb_build_object('id',term_id,'code',fixture_code,'name','非法选定租户编辑','days',30)); exception when insufficient_privilege then blocked:=true; end;
  if not blocked then raise exception 'Platform-selected cross-tenant edit was accepted'; end if;
  perform set_config('request.jwt.claim.sub',ordinary_actor::text,true);
  perform set_config('request.headers','{}',true);
  listing:=public.fms_purchase_payable_list_secure('estimated','',document_id,20,0,'{}');
  if jsonb_array_length(listing->'data')<>1 then raise exception 'Authorized ordinary user could not read own payable'; end if;
  listing:=public.fms_payable_currency_context_secure('estimated','2026-10-21','CNY',ordinary_tenant,document_id);
  if not(listing->>'configured')::boolean then raise exception 'Ordinary own currency context denied';end if;
  listing:=public.fms_payable_options_secure('tax',ordinary_tenant);
  if not exists(select 1 from jsonb_array_elements(listing) rate where rate->>'code'='13') then raise exception 'Ordinary payable user cannot select the shared tax dictionary'; end if;
  document:=public.fms_save_purchase_payable_secure(document||jsonb_build_object('remark','普通用户编辑'));
  perform set_config('request.headers',jsonb_build_object('x-art-tenant-scope',other_tenant)::text,true);
  if app_private.current_read_tenant_id()<>ordinary_tenant then raise exception 'Forged header changed ordinary scope'; end if;
  listing:=public.fms_purchase_payable_list_secure('estimated','',document_id,20,0,'{}');
  if jsonb_array_length(listing->'data')<>1 then raise exception 'Forged header hid own payable'; end if;
  listing:=public.fms_payable_currency_context_secure('estimated','2026-10-21','CNY',ordinary_tenant,document_id);
  if not(listing->>'configured')::boolean then raise exception 'Forged header changed ordinary currency context';end if;
  blocked:=false;begin perform public.fms_payable_currency_context_secure('estimated','2026-10-21','CNY',other_tenant,null);exception when insufficient_privilege then blocked:=true;end;
  if not blocked then raise exception 'Ordinary currency context allowed explicit foreign tenant';end if;
  blocked:=false;
  begin perform public.fms_save_purchase_payable_secure(payload||jsonb_build_object('tenant_id',other_tenant)); exception when insufficient_privilege then blocked:=true; end;
  if not blocked then raise exception 'Ordinary cross-tenant create was accepted'; end if;
  blocked:=false;
  begin perform public.fms_act_purchase_payable_secure(array[document_id],'submit'); exception when insufficient_privilege then blocked:=true; end;
  if not blocked then raise exception 'Missing Submit permission was bypassed'; end if;
  term_id:=public.mdm_save_payment_term_secure(jsonb_build_object('code',fixture_code,'name','普通租户付款条件','days',45));
  if (select tenant_id from public.mdm_payment_term where id=term_id)<>ordinary_tenant then raise exception 'Forged header changed root write tenant'; end if;
  delete from public.sys_role_menu where role_id=fixture_role and menu_id in(select id from public.sys_menu where name='FinanceEstimatedPayable:View');
  blocked:=false;
  begin perform public.fms_payable_options_secure('supplier'); exception when insufficient_privilege then blocked:=true; end;
  if not blocked then raise exception 'Payment-term-only permission leaked payable supplier options'; end if;
  blocked:=false;begin perform public.fms_payable_currency_context_secure('estimated','2026-10-21','CNY',ordinary_tenant,document_id);exception when insufficient_privilege then blocked:=true;end;
  if not blocked then raise exception 'Payment-term-only permission leaked payable currency context';end if;
  if has_table_privilege('authenticated','public.fms_purchase_payable_document','INSERT') or has_table_privilege('authenticated','public.fms_purchase_payable_line','DELETE') then raise exception 'Payable direct writes bypass secured RPCs'; end if;
end $test$;
rollback;
