  tools(drawer).getByRole('button', { name: '下载 OpenAPI 规范', exact: true })
const viewer = (page: Page) => page.getByRole('dialog', { name: 'OpenAPI 规范', exact: true })
const viewerCode = (page: Page) => viewer(page).locator('pre[aria-label="接口规范代码"] code')

async function integration(drawer: Locator) {
  await drawer.getByRole('tab', { name: '接入说明', exact: true }).click()
  await expect(tools(drawer)).toBeVisible()
}

async function closePreview(page: Page) {
  await viewer(page).getByRole('button', { name: '关闭', exact: true }).last().click()
  await expect(viewer(page)).toBeHidden()
}

async function previewDocument(page: Page, drawer: Locator) {
  await previewButton(drawer).click()
  await expect(viewer(page)).toBeVisible()
  const text = await viewerCode(page).textContent()
  const parsed: unknown = JSON.parse(text || 'null')
  return { text: text || '', document: toObjectRecord(parsed) }
}

async function downloadDocument(page: Page, drawer: Locator, info: TestInfo, slug: string) {
  const pending = page.waitForEvent('download')
  await downloadButton(drawer).click()
  const download = await pending
  expect(download.suggestedFilename()).toBe(`${slug}.openapi.json`)
  // Preserve the actual browser-generated bytes for root's official-schema validation.
  const artifact = info.outputPath('query-api.openapi.json')
  await download.saveAs(artifact)
  const text = await readFile(artifact, 'utf8')
  const parsed: unknown = JSON.parse(text)
  return { text, document: toObjectRecord(parsed), artifact }
}

function requestDefinition(document: Record<string, unknown>, slug: string) {
  const pathname = `/functions/v1/sql-query-api/${slug}`
  const paths = toObjectRecord(document.paths)
  expect(Object.keys(paths)).toEqual([pathname])
  const path = toObjectRecord(paths[pathname])
  expect(Object.keys(path)).toEqual(['post'])
  const operation = toObjectRecord(path.post)
  const request = toObjectRecord(operation.requestBody)
  const json = toObjectRecord(toObjectRecord(request.content)['application/json'])
  const body = toObjectRecord(json.schema)
  const properties = toObjectRecord(body.properties)
  const params = toObjectRecord(properties.params)
  return {
    operation,
    request,
    json,
    body,
    properties,
    params,
    fields: toObjectRecord(params.properties)
  }
}

function alternatives(value: unknown): Record<string, unknown>[] {
  const items = toObjectRecord(value).anyOf
  return Array.isArray(items) ? items.map(toObjectRecord) : []
}

