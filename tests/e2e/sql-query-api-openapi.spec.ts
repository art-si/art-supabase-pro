function deferred() {
  let release!: () => void
  const wait = new Promise<void>((resolve) => {
    release = resolve
  })
  return { wait, release }
}

const tools = (drawer: Locator) =>
  drawer.getByRole('region', { name: 'OpenAPI 规范工具', exact: true })
const previewButton = (drawer: Locator) =>
  tools(drawer).getByRole('button', { name: '预览 OpenAPI 规范', exact: true })
