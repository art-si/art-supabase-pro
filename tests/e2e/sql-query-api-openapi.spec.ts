interface FixtureOptions {
  ordinary?: boolean
  cached?: boolean
  definitions?: SqlQueryApiDefinition[]
}

async function prepare(page: Page, project: string, options: FixtureOptions = {}) {
  page.setDefaultTimeout(15_000)
  page.setDefaultNavigationTimeout(60_000)
  await prepareIsolatedSession(page)
  const appearance = {
    theme: project.includes('dark') ? 'dark' : 'light',
    boxBorderMode: !project.includes('shadow')
  } as const
  await prepareAppearance(page, appearance)
  await page.addInitScript((appearance) => {
    const apply = () => {
      document.documentElement.dataset.boxMode = appearance.boxBorderMode
        ? 'border-mode'
        : 'shadow-mode'
      document.documentElement.dataset.uiScope = 'admin'
    }
    if (document.documentElement) apply()
    else document.addEventListener('DOMContentLoaded', apply, { once: true })
  }, appearance)
  const ordinary = options.ordinary ?? true
  const state = {
    definitions: structuredClone(options.definitions ?? [definition, secondary]),
    lists: 0,
    invokes: [] as Record<string, unknown>[],
    mutations: [] as Record<string, unknown>[],
    rawExecutions: 0,
    invocationWait: undefined as Promise<void> | undefined,
    listWait: undefined as Promise<void> | undefined
  }
  await page.route('**/functions/v1/execute-sql-with-columns', (route) => {
    const body = route.request().postDataJSON() as Record<string, unknown>
    if (body.action !== 'metadata') state.rawExecutions++
    return route.fulfill({
      json: { schemas: [], tables: [], columns: [], functions: [], foreignKeys: [] }
    })
  })
  await page.route('**/functions/v1/sql-query-api**', async (route) => {
    const body = route.request().postDataJSON() as Record<string, unknown>
    if (body.action === 'list') {
      state.lists++
      await state.listWait
      return route.fulfill({
        json: { definitions: state.definitions, canManage: !ordinary, users: [] }
      })
    }
    if (body.action) {
      state.mutations.push(body)
      return route.fulfill({ status: 400, json: { message: '导出规范不应触发服务端写操作' } })
    }
    state.invokes.push(body)
    await state.invocationWait
    return route.fulfill({
      json: {
        status: 'ok',
        rows: [{ OPENAPI_PRIVATE_RESULT: privateResult }],
        columns: [{ name: 'OPENAPI_PRIVATE_RESULT' }],
        rowCount: 1,
        truncated: false,
        durationMs: 3,
        maxRows: 200,
        timeoutMs: 10000
      }
    })
  })
  await page.goto(
    `/tests/e2e/fixtures/sql-console-metadata.html?actor=${actor}&tenant=${tenantA}${ordinary ? '&ordinary=1' : ''}${options.cached ? '&keepalive=1' : ''}`
  )
  await expect(page.locator('.monaco-editor')).toBeVisible()
  await assertAppearance(page, appearance)
  const drawer = page.getByRole('dialog', { name: '查询 API', exact: true })
  const open = async () => {
    await page.getByRole('button', { name: '查询 API', exact: true }).click()
    await expect(drawer).toBeVisible()
    await expect(drawer.getByRole('tab', { name: '接入说明', exact: true })).toBeVisible()
  }
  const refresh = async () => {
    const previous = state.lists
    await drawer.getByRole('button', { name: '刷新 API', exact: true }).click()
    await expect.poll(() => state.lists).toBe(previous + 1)
    await expect(drawer.getByRole('button', { name: '刷新 API', exact: true })).toBeEnabled()
  }
  await open()
  return { state, drawer, open, refresh }
}

/** Exercise owner changes in the same event turn as opening a child preview. */
async function previewWithConcurrentCommand(command: Locator) {
  await command.evaluate((button) => {
    const parent = button.closest('[role="dialog"]')
    const preview = parent?.querySelector<HTMLButtonElement>(
      'button[aria-label="预览 OpenAPI 规范"]'
    )
    if (!(button instanceof HTMLButtonElement) || button.disabled || !preview || preview.disabled)
      throw new Error('The intended OpenAPI owner-change commands are unavailable')
    preview.click()
    button.click()
  })
}

